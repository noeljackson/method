#!/usr/bin/env python3
"""Build the Noel Method runtime pack and equivalent monolith."""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
from pathlib import Path

from methodlib import PROTOCOL_KEYS, context_spec


ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
PACK = DIST / "pack"
SCHEMAS = (
    "project-policy.schema.json",
    "policy-authorities.schema.json",
    "task-request.schema.json",
    "resolved-permissions.schema.json",
    "program-control.schema.json",
)


def read(source: str) -> str:
    return (ROOT / source).read_text(encoding="utf-8").strip()


def generated_header(version: str) -> str:
    return (
        "<!-- Generated by scripts/build_dist.py; do not edit directly. -->\n"
        f"<!-- Noel Method version {version}. -->\n"
    )


def navigation(prefix: str = "") -> str:
    return f"[Index]({prefix}INDEX.md) · [Kernel]({prefix}KERNEL.md)\n"


def modular_document(version: str, content: str, prefix: str = "") -> str:
    return generated_header(version) + "\n" + navigation(prefix) + "\n" + content + "\n"


def render_index(version: str, spec: dict[str, object]) -> str:
    protocols = spec["protocols"]
    return generated_header(version) + f"""
# Noel Method Runtime Pack

Version: `{version}`

## Default: direct mode

Load [Kernel](KERNEL.md). The current request and canonical project
instructions supply authority. Direct mode may include external or persistent
work when those sources authorize its scope, actions, gates, and prohibitions.
Do not create Method artifacts merely because work has several steps, uses a
remote service, or persists across a conversation.

Load protocols by task shape:

| Protocol | Task signal | Module |
| --- | --- | --- |
| `program` | `{protocols['program']['task_signal']}` | [Program](protocols/program.md) |
| `experiment` | `{protocols['experiment']['task_signal']}` | [Experiment](protocols/experiment.md) |
| `secrets` | `{protocols['secrets']['task_signal']}` | [Secrets](protocols/secrets.md) |

Protocols add procedure, never permission.

## Optional: resolved mode

Use resolved mode only when the project, current request, or consuming host
explicitly selects it. The host authenticates the TaskRequest, protects the
accepted ProjectPolicy and authority registry, runs the deterministic resolver,
and enforces ResolvedPermissions:

```sh
python3 tools/noel_method.py resolve \\
  --policy PROJECT-POLICY.json \\
  --authorities POLICY-AUTHORITIES.json \\
  --task TASK-REQUEST.json
```

Load [Kernel](KERNEL.md), TaskRequest, ResolvedPermissions, and exactly the
protocol modules named by `protocols`. If resolved mode is selected and its
permissions are missing, unverified, expired, or inconsistent with current
state, remain read-only.

When Program is selected, separately validate and supply the ProgramControl
named by the TaskRequest:

```sh
python3 tools/noel_method.py validate-program-control PROGRAM-CONTROL.json
```

This validates structure and terminal-state invariants only. The harness must
still bind the control to current canonical state and authority.

The model may request another protocol when risk emerges. Only the resolver may
issue updated ResolvedPermissions in resolved mode; the model cannot remove a
protocol, widen actions, or downgrade the authority mode.

Machine-readable routing and schemas are in [CONTEXT.json](CONTEXT.json) and
[`schemas/`](schemas/).

## Single-file fallback

Use [`../MONOLITH.md`](../MONOLITH.md) only when linked modules cannot be
loaded. It contains the same Kernel and all three protocols. It does not grant
project authority or select resolved mode.
""".lstrip()


def render_all() -> dict[Path, str]:
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    spec = context_spec()
    kernel = read("src/KERNEL.md")
    protocol_content = {
        key: read(f"protocols/{key}.md") for key in PROTOCOL_KEYS
    }
    monolith = generated_header(version) + "\n" + "\n\n---\n\n".join(
        [kernel, *(protocol_content[key] for key in PROTOCOL_KEYS)]
    ) + "\n"
    rendered: dict[Path, str] = {
        DIST / "MONOLITH.md": monolith,
        PACK / "INDEX.md": render_index(version, spec),
        PACK / "CONTEXT.json": json.dumps(
            {"method": "Noel Method", "version": version, **spec},
            indent=2,
        ) + "\n",
        PACK / "KERNEL.md": modular_document(version, kernel),
        PACK / "tools" / "noel_method.py": (
            f"# Generated from scripts/methodlib.py for Noel Method {version}.\n"
            + (ROOT / "scripts" / "methodlib.py").read_text(encoding="utf-8")
        ),
    }
    for key in PROTOCOL_KEYS:
        rendered[PACK / "protocols" / f"{key}.md"] = modular_document(
            version, protocol_content[key], prefix="../"
        )
    for schema in SCHEMAS:
        rendered[PACK / "schemas" / schema] = (
            ROOT / "schemas" / schema
        ).read_text(encoding="utf-8")

    manifest_files = [
        {
            "path": str(path.relative_to(PACK)),
            "sha256": hashlib.sha256(content.encode()).hexdigest(),
        }
        for path, content in rendered.items()
        if PACK in path.parents
    ]
    manifest_files.sort(key=lambda item: item["path"])
    rendered[PACK / "MANIFEST.json"] = json.dumps(
        {
            "method": "Noel Method",
            "version": version,
            "entrypoint": "INDEX.md",
            "kernel": "KERNEL.md",
            "protocols": list(PROTOCOL_KEYS),
            "files": manifest_files,
        },
        indent=2,
    ) + "\n"
    return rendered


def check(rendered: dict[Path, str]) -> int:
    failed = False
    for path, expected in rendered.items():
        actual = path.read_text(encoding="utf-8") if path.exists() else ""
        if actual == expected:
            continue
        failed = True
        diff = difflib.unified_diff(
            actual.splitlines(), expected.splitlines(),
            fromfile=str(path.relative_to(ROOT)), tofile="generated", lineterm="",
        )
        print("\n".join(diff))
    expected_pack = {path for path in rendered if PACK in path.parents}
    actual_pack = {
        path for path in PACK.rglob("*") if path.is_file()
    } if PACK.exists() else set()
    extras = sorted(actual_pack - expected_pack)
    if extras:
        failed = True
        print("unexpected generated pack files:")
        for path in extras:
            print(f"- {path.relative_to(ROOT)}")
    return 1 if failed else 0


def previous_generated_files() -> set[Path]:
    manifest = PACK / "MANIFEST.json"
    if not manifest.is_file():
        return set()
    try:
        value = json.loads(manifest.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return set()
    if not isinstance(value, dict) or not isinstance(value.get("files"), list):
        return set()
    return {
        PACK / item["path"]
        for item in value["files"]
        if isinstance(item, dict) and isinstance(item.get("path"), str)
    }


def write(rendered: dict[Path, str]) -> None:
    previous = previous_generated_files()
    for path, content in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    expected_pack = {path for path in rendered if PACK in path.parents}
    for path in sorted(
        (item for item in PACK.rglob("*") if item.is_file()), reverse=True
    ):
        if path in expected_pack:
            continue
        if path not in previous:
            text = path.read_text(encoding="utf-8", errors="replace")
            if not text.startswith("<!-- Generated by scripts/build_dist.py"):
                raise RuntimeError(
                    f"refusing to remove non-generated file: {path.relative_to(ROOT)}"
                )
        path.unlink()
        print(f"removed stale {path.relative_to(ROOT)}")
    for directory in sorted(
        (item for item in PACK.rglob("*") if item.is_dir()), reverse=True
    ):
        if not any(directory.iterdir()):
            directory.rmdir()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render_all()
    return check(rendered) if args.check else (write(rendered) or 0)


if __name__ == "__main__":
    raise SystemExit(main())
